#!/usr/bin/env bash
# Regenerates src/icons.ts from the Secret Keeper site icons. The server is
# a single Node process with no static files on disk, so the PNGs for the
# landing page (logo and favicon) are embedded as base64.
#   ./scripts/embed_icons.sh [path/to/secret_keeper_site/public]
set -euo pipefail
src="${1:-$(dirname "$0")/../../secret_keeper/site/public}"
out="$(dirname "$0")/../src/icons.ts"
{
  echo "// Generated by scripts/embed_icons.sh from the secretkeeper.net icons. Do not edit."
  echo "export const ICON_32_PNG = Buffer.from('$(base64 < "$src/icon-32.png" | tr -d '\n')', 'base64');"
  echo "export const ICON_128_PNG = Buffer.from('$(base64 < "$src/icon-128.png" | tr -d '\n')', 'base64');"
} > "$out"
echo "wrote $out"
